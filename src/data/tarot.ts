const dayFormat = new Intl.DateTimeFormat('en', {
  timeZone: 'Europe/Oslo', year: 'numeric', month: '2-digit', day: '2-digit',
});

export const tarotPositions = ['Situation', 'Challenge', 'Advice'] as const;

export function dailyTarot(now: Date) {
  const parts = Object.fromEntries(dayFormat.formatToParts(now).map(part => [part.type, part.value]));
  const day = `${parts.year}-${parts.month}-${parts.day}`;
  let seed = 2166136261;
  for (const character of day) seed = Math.imul(seed ^ character.charCodeAt(0), 16777619);
  function random() {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    return seed / 4294967296;
  }

  const remaining = tarotCards.map((_, index) => index);
  const cards = tarotPositions.map(position => {
    const [index] = remaining.splice(Math.floor(random() * remaining.length), 1);
    const card = tarotCards[index];
    const reversed = random() < .5;
    const number = String(index).padStart(2, '0');
    return {
      position,
      name: card.name,
      reversed,
      meaning: reversed ? card.reversed : card.upright,
      image: `/tarot/${number}.jpg`,
    };
  });
  return { day, cards };
}
